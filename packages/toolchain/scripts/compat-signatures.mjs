/**
 * Reads the engine's compat declarations (`packages/engine/dist-types/compat`)
 * and reduces every exported function to the kind of each caller-supplied
 * parameter, so the emitter can coerce a GML argument (a number standing in
 * for a boolean, a runtime value standing in for a string) to what the compat
 * function declares. Run `node scripts/compat-signatures.mjs` to rewrite
 * `src/gml/lower/compat-signatures.ts`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const compatDir = path.resolve(here, "../../engine/dist-types/compat");
export const OUT = path.resolve(here, "../src/gml/lower/compat-signatures.ts");

/** The entity and context parameters the emitter threads in itself. */
const THREADED = /^(Entity|Gml\w*Context)$/;

function kindOf(type) {
  if (type === undefined) return "other";
  const text = type.getText().replace(/\s+/g, " ");
  const parts = text.split("|").map((p) => p.trim());
  const real = parts.filter((p) => p !== "undefined" && p !== "null");
  if (real.length === 1) {
    if (real[0] === "number") return "number";
    if (real[0] === "string") return "string";
    if (real[0] === "boolean") return "boolean";
  }
  if (real.length === 1 && /(\[\]$|^(Readonly)?Array<)/.test(real[0]))
    return "array";
  if (real.length === 2 && real.includes("true") && real.includes("false"))
    return "boolean";
  return "other";
}

export function generate() {
  const table = {};
  for (const file of fs.readdirSync(compatDir).sort()) {
    if (!file.endsWith(".d.ts")) continue;
    const sf = ts.createSourceFile(
      file,
      fs.readFileSync(path.join(compatDir, file), "utf8"),
      ts.ScriptTarget.Latest,
      true,
    );
    for (const st of sf.statements) {
      if (!ts.isFunctionDeclaration(st) || !st.name) continue;
      if (!st.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword))
        continue;
      const kinds = [];
      for (const p of st.parameters) {
        const t = p.type?.getText();
        if (t !== undefined && THREADED.test(t)) continue;
        if (p.dotDotDotToken) break;
        kinds.push(kindOf(p.type));
      }
      if (kinds.some((k) => k !== "other"))
        table[st.name.text] ??= kinds.join(",");
    }
  }
  return table;
}

export function render(table) {
  const rows = Object.entries(table)
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
    .join("\n");
  return `// Generated by scripts/compat-signatures.mjs from the engine's compat declarations. Do not edit.
/** Compat function -> comma-separated kinds of its caller-supplied parameters (entity and context excluded). */
export const COMPAT_PARAM_KINDS: Readonly<Record<string, string>> = {
${rows}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  fs.writeFileSync(OUT, render(generate()));
